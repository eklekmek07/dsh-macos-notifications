import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
await mkdir(new URL('../lib/', import.meta.url), { recursive: true })
await build({
  absWorkingDir: root, entryPoints: ['src/index.js'], outfile: 'lib/index.js', bundle: true,
  format: 'esm', platform: 'node', target: 'node22', external: ['@deepseek-ai/schemastery', 'zod'],
  legalComments: 'inline',
})
const result = await build({
  absWorkingDir: root, entryPoints: ['src/client.jsx'], bundle: true, write: false,
  format: 'cjs', platform: 'browser', target: 'es2022', jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'], loader: { '.css': 'text' }, legalComments: 'inline',
})
const code = `// Generated by pnpm build. Edit src/, not this file.\nwindow.__ModuleLoader__.load({id:"dsh-macos-notifications",factory:(require)=>{var module={exports:{}};var exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports;}});\n`
await writeFile(new URL('../lib/client.js', import.meta.url), code)
console.log('Built Host and DSH Client modules without modifying the DSH application.')
